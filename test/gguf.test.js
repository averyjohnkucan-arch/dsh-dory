import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, rm, writeFile, open } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { inspectGguf } from "../lib/gguf.js";
import { gguf } from "./model-fixture.js";
test("header inspection rejects truncated and oversized metadata without reading weight payloads", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "dory-gguf-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const path = join(root, "model.gguf");
  await writeFile(path, "GGUF");
  await assert.rejects(inspectGguf(path), /Truncated/);
  await gguf(path);
  const file = await open(path, "r+");
  const bad = Buffer.alloc(8);
  bad.writeBigUInt64LE(20001n);
  await file.write(bad, 0, 8, 16);
  await file.close();
  await assert.rejects(inspectGguf(path), /exceeds inspection/);
  await gguf(path);
  const padded = await open(path, "r+");
  await padded.truncate(8 * 1024 ** 3);
  await padded.close();
  const result = await inspectGguf(path);
  assert.equal(result.architecture, "dory");
  assert.equal(result.bytes, 8 * 1024 ** 3);
  await assert.rejects(inspectGguf(path, AbortSignal.abort()), /abort/i);
});
